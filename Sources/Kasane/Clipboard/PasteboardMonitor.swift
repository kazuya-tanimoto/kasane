import AppKit
import KasaneStore

/// メインスレッドでクリップボードから読み取った、加工前の内容
struct RawCapture: @unchecked Sendable {
    var representations: [Capture.Representation]
    var fileURLs: [URL]
    var string: String?
    var types: Set<String>
    var sourceBundleID: String?
    var sourceAppName: String?
}

/// クリップボードの変更を監視する。
///
/// NSPasteboard には変更通知がないので、`changeCount` を短い間隔で確認する。
/// `changeCount` の確認だけなら中身を読まないので、プライバシーの確認アラートは出ない。
@MainActor
final class PasteboardMonitor {
    /// パスワードマネージャーなどが「履歴に残さないで」と付ける型（nspasteboard.org の取り決め）
    static let ignoredMarkerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    var onCapture: ((RawCapture) -> Void)?

    private let pasteboard = NSPasteboard.general
    private let writer: PasteboardWriter
    private var lastChangeCount: Int
    private var timer: Timer?

    init(writer: PasteboardWriter) {
        self.writer = writer
        // 起動前からクリップボードにあるものは取り込まない
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        timer?.invalidate()
        let timer = Timer(timeInterval: AppSettings.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        // Kasane 自身が書き込んだもの（貼り付けや FIFO/LIFO の入れ替え）は新しいコピーとして扱わない
        guard !writer.isOwnChange(changeCount) else { return }
        // 「他のアプリからのペースト」が拒否されていれば読めない
        guard Permissions.pasteboardAccess != .denied else { return }
        guard let types = pasteboard.types, !types.isEmpty else { return }
        let typeNames = Set(types.map(\.rawValue))
        guard typeNames.isDisjoint(with: Self.ignoredMarkerTypes) else { return }

        let app = NSWorkspace.shared.frontmostApplication
        if let bundleID = app?.bundleIdentifier, AppSettings.excludedBundleIDs.contains(bundleID) {
            return
        }

        var representations: [Capture.Representation] = []
        for (index, item) in (pasteboard.pasteboardItems ?? []).enumerated() {
            for type in item.types where !Self.shouldSkip(type.rawValue) {
                guard let data = item.data(forType: type), data.count <= HistoryStore.maxRepresentationSize else {
                    continue
                }
                representations.append(.init(itemIndex: index, type: type.rawValue, data: data))
            }
        }
        guard !representations.isEmpty else { return }

        let fileURLs = (pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL]) ?? []

        onCapture?(RawCapture(
            representations: representations,
            fileURLs: fileURLs,
            string: pasteboard.string(forType: .string),
            types: typeNames,
            sourceBundleID: app?.bundleIdentifier,
            sourceAppName: app?.localizedName
        ))
    }

    /// 保存しない型。`dyn.` は他のアプリが一時的に作る型で、貼り付けの再現には要らない
    static func shouldSkip(_ type: String) -> Bool {
        type.hasPrefix("dyn.")
    }
}
